"use strict";
const test = require("node:test");
const assert = require("node:assert");
const lib = require("../lib");

const TIERS = {
    tiers: {
        auto: { paths: ["src/locales/*/parsers/**", "src/locales/*/refiners/**", "tests/locales/**"] },
        "auto-strict": { paths: ["src/core/**", "src/calculation/**", "src/common/**"], start_as: "human" },
        human: { paths: [".github/**", "contracts/**", "harness/**"] },
    },
};

const taskmap = {
    upstream_root: "upstream/src",
    done: [{ step: "Done", rust: "src/locales/en/parsers/done.rs" }],
    tasks: [
        { id: "en/a-parser", step: "A", source: "locales/en/parsers/A.ts", rust: "src/locales/en/parsers/a.rs", area: "x" },
        { id: "en/b-refiner", step: "B", source: "locales/en/refiners/B.ts", rust: "src/locales/en/refiners/b.rs", area: "y" },
        { id: "common/c-refiner", step: "C", source: "common/refiners/C.ts", rust: "src/common/refiners/c.rs", area: "z" },
    ],
    acceptance: { differential: { phrases: 2000, seed: 42 }, clippy: "deny-warnings", public_api: "unchanged-except-added" },
};
const upstreamFiles = new Map([
    ["upstream/src/locales/en/parsers/A.ts", "export default class A extends X {}"],
    ["upstream/src/locales/en/refiners/B.ts", "export default class B {}"],
    ["upstream/src/common/refiners/C.ts", "export default class C {}"],
]);
const configurations = { "en.casual": { parsers: [{ name: "A" }, { name: "Done" }], refiners: [{ name: "B" }, { name: "C" }] } };
const cases = [
    { area: "en/a", requires: ["A"] },
    { area: "en/a", requires: ["A", "B"] },
    { area: "en/b", requires: ["B", "A", "Done"] },
    { area: "en/b", requires: ["B", "C", "A"] },
    { area: "en/c", requires: ["C", "Done"] },
];
const pin = { commit: "d4fe7e39015c818b271d74789fb96f74777421d0" };

test("validate accepts a consistent map", () => {
    assert.deepStrictEqual(lib.validate({ taskmap, upstreamFiles, configurations }), []);
});

test("validate catches missing steps, duplicates, wrong class and bad paths", () => {
    const bad = {
        ...taskmap,
        tasks: [
            ...taskmap.tasks,
            { id: "en/a-parser", step: "A", source: "locales/en/parsers/A.ts", rust: "src/core/a.rs", area: "x" },
            { id: "en/d", step: "D", source: "locales/en/parsers/A.ts", rust: "src/locales/en/parsers/d.rs", area: "x" },
        ],
    };
    const cfg = { "en.casual": { parsers: [{ name: "Missing" }], refiners: [] } };
    const p = lib.validate({ taskmap: bad, upstreamFiles, configurations: cfg }).join("\n");
    assert.match(p, /duplicate id en\/a-parser/);
    assert.match(p, /duplicate step A/);
    assert.match(p, /rust path must be one file/);
    assert.match(p, /has no class D/);
    assert.match(p, /Missing is neither done nor a task/);
});

test("tiers come from policy; unknown paths are human", () => {
    assert.strictEqual(lib.tierFor(["src/locales/en/parsers/a.rs"], TIERS), "auto");
    assert.strictEqual(lib.tierFor(["src/common/refiners/c.rs"], TIERS), "human");
    assert.strictEqual(lib.tierFor(["src/other.rs"], TIERS), "human");
});

test("contracts: deps from the cheapest golden case, priority by golden count, deterministic", () => {
    const a = lib.buildContracts({ taskmap, pin, tiers: TIERS, cases });
    const b = lib.buildContracts({ taskmap, pin, tiers: TIERS, cases });
    assert.deepStrictEqual(a, b);
    const byId = Object.fromEntries(a.map((c) => [c.id, c]));
    assert.deepStrictEqual(byId["en/a-parser"].depends_on, []);
    assert.deepStrictEqual(byId["en/b-refiner"].depends_on, ["en/a-parser"]); // A+B+Done is cheaper than A+B+C
    assert.deepStrictEqual(byId["common/c-refiner"].depends_on, []);
    assert.deepStrictEqual(byId["en/a-parser"].acceptance[0], { golden: { step: "A", areas: ["en/a", "en/b"] } });
    assert.strictEqual(byId["en/a-parser"].priority, 1); // 4 cases
    assert.strictEqual(byId["common/c-refiner"].tier, "human");
    assert.strictEqual(byId["en/a-parser"].source_sha, pin.commit);
    assert.deepStrictEqual(byId["en/a-parser"].scope, ["src/locales/en/parsers/a.rs"]);
    const text = lib.renderContract(byId["en/b-refiner"]);
    assert.match(text, /^# Generated by scripts\/seed-backlog\/seed.js/);
    assert.match(text, /depends_on:\n {2}- en\/a-parser/);
});

test("cycles and steps without golden cases fail", () => {
    const cyc = [
        { area: "x", requires: ["A", "B"] },
        { area: "x", requires: ["B", "A"] },
        { area: "x", requires: ["C"] },
    ];
    assert.throws(() => lib.buildContracts({ taskmap, pin, tiers: TIERS, cases: cyc }), /dependency cycle/);
    assert.throws(() => lib.buildContracts({ taskmap, pin, tiers: TIERS, cases: [{ area: "x", requires: ["A"] }] }), /no golden case needs/);
});

test("issue plan has the hidden marker and no factory:ready label", () => {
    const plan = lib.planIssues(lib.buildContracts({ taskmap, pin, tiers: TIERS, cases }), "o/r");
    for (const p of plan) {
        assert.ok(p.body.startsWith(p.marker));
        assert.ok(!p.labels.includes("factory:ready"));
    }
    assert.deepStrictEqual(plan.find((p) => p.marker.includes("en/b-refiner")).blocked_by, ["en/a-parser"]);
});

test("rust paths the registry skips are rejected (mod.rs, _helpers)", () => {
    for (const rust of ["src/locales/en/parsers/mod.rs", "src/locales/en/parsers/_helper.rs", "src/locales/en/parsers/Bad.rs"]) {
        const bad = { ...taskmap, tasks: [{ ...taskmap.tasks[0], rust }, ...taskmap.tasks.slice(1)] };
        assert.match(lib.validate({ taskmap: bad, upstreamFiles, configurations }).join("\n"), /rust path must be one file/, rust);
    }
});

test("re-run keeps owner labels and replaces managed ones", () => {
    const merged = lib.mergeLabels(["factory:ready", "tier:human", "area:old", "factory:task", "needs-human"], ["factory:task", "tier:auto", "area:x"]);
    assert.deepStrictEqual(merged, ["area:x", "factory:ready", "factory:task", "needs-human", "tier:auto"]);
});

test("missingLabels: only the absent ones, first definition wins, existing never touched", () => {
    const req = [{ name: "factory:task" }, { name: "factory:revert-reviewed", color: "0E8A16" }, { name: "area:x" }, { name: "factory:revert-reviewed", color: "000000" }];
    assert.deepStrictEqual(lib.missingLabels(req, ["factory:task", "area:x"]), [{ name: "factory:revert-reviewed", color: "0E8A16" }]);
    assert.deepStrictEqual(lib.missingLabels(req, ["factory:task", "factory:revert-reviewed", "area:x"]), []);
});
